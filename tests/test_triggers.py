def test_function_folders_and_tags_cover_old_and_new_minecraft(mc_dir):
    make_model(mc_dir, "m")
    triggers.install_model(mc_dir, "m")
    data = os.path.join(triggers._pack_dir(mc_dir), "data")
    for folder in mcf.FUNCTION_DIRS:
        assert os.path.isfile(os.path.join(data, "pdb2mc", folder, "tick.mcfunction"))
        assert os.path.isfile(os.path.join(data, "pdb2mc", folder, "job", "try.mcfunction"))
        with open(os.path.join(data, "minecraft", "tags", folder, "load.json")) as f:
            # Not required: a version that can't load the function must not lose the whole tag
            assert json.load(f) == {"values": [{"id": "pdb2mc:load", "required": False}]}


def test_macro_lines_use_only_known_arguments(mc_dir):
    make_model(mc_dir, "m")
    triggers.install_model(mc_dir, "m")
    for name, text in all_functions(mc_dir).items():
        for line in text.splitlines():
            arguments = re.findall(r"\$\(([a-z]+)\)", line)
            if arguments:
                assert line.startswith("$"), (name, line)
                assert set(arguments) <= {"name", "x", "y", "z", "dim", "action"}, (name, line)
            elif line.startswith("$"):
                pytest.fail(f"macro line without an argument, which Minecraft rejects: {name}: {line}")


def test_no_filter_directly_after_a_list_index(mc_dir):
    """
    jobs[0]{a:1} is not a valid NBT path. Minecraft parses macro lines only when they run, and a bad line aborts
    the whole function, which here would leave the queue stuck until the next /reload.
    """
    make_model(mc_dir, "m")
    triggers.install_model(mc_dir, "m")
    for name, text in all_functions(mc_dir).items():
        assert not re.search(r"\[-?\d+\]\{", text), name


def test_every_called_function_exists(mc_dir):
    make_model(mc_dir, "m")
    triggers.install_model(mc_dir, "m")
    functions = all_functions(mc_dir)
    texts = list(functions.values()) + [protein_function(mc_dir, "build_m"), protein_function(mc_dir, "clear_m")]
    for text in texts:
        for called in re.findall(r"function pdb2mc:(\S+)", text):
            if "$" not in called:                       # filled in when it runs
                assert called in functions, called


def test_footprint_covers_blocks_on_both_sides_of_the_origin(mc_dir):
    make_model(mc_dir, "wide", positions=((-300, 0, -100), (120, 0, 10)))
    triggers.install_model(mc_dir, "wide")
    x1, z1, x2, z2 = triggers.models(mc_dir)["wide"]["extent"]
    assert (x1, z1, x2, z2) == (-260, -60, 160, 50)        # blocks sit 40 from the origin on X and Z
    loaded = pdb2mc_function(mc_dir, "models/wide/loaded")
    assert f"unless loaded ~{x1} ~ ~{z1} " in loaded and f"unless loaded ~{x2} ~ ~{z2} " in loaded
    load = pdb2mc_function(mc_dir, "models/wide/load")
    for line in load.splitlines():
        a, b, c, d = (int(value.lstrip("~")) for value in line.split()[2:])
        assert (c - a) // 16 + 2 <= 16 and (d - b) // 16 + 2 <= 16   # at most 256 chunks in one command
    assert pdb2mc_function(mc_dir, "models/wide/unload").replace("remove", "add") == load


