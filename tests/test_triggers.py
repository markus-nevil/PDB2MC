def build_config(mc_dir, **changes):
    config = defaults.default_config("Skeleton")
    config.update(pdb_file=preset("Helix"), save_path=mc_dir, **changes)
    return config


def test_build_model_adds_triggers_only_when_asked(mc_dir):
    """The web server builds into a public world: visitors must not get build and delete commands there."""
    build.build_model("Skeleton", build_config(mc_dir))
    assert triggers.models(mc_dir) == {}
    assert not os.path.exists(os.path.join(triggers._pack_dir(mc_dir), "data", "pdb2mc"))
    assert "place template" in protein_function(mc_dir, "build_helix")

    build.build_model("Skeleton", build_config(mc_dir, triggers=True))
    assert triggers.model_number(mc_dir, "helix") == 1


def test_default_config_leaves_triggers_off():
    for mode in defaults.MODES:
        assert not defaults.default_config(mode).get('triggers')


def test_command_line_builds_with_triggers(tmp_path, capsys):
    world = tmp_path / "saves" / "world"
    world.mkdir(parents=True)
    assert cli.main(["Skeleton", preset("Helix"), str(world), "--name", "My Helix"]) == 0
    assert "/trigger build set 1" in capsys.readouterr().out
    assert triggers.model_number(cli.datapack_dir(str(world)), "my-helix") == 1


