def test_removing_all_files_forgets_the_models(mc_dir):
    make_model(mc_dir, "m")
    triggers.install_model(mc_dir, "m")
    mcf.delete_nbt_mcfunctions_from_dir(mc_dir)
    triggers.sync(mc_dir)
    assert triggers.models(mc_dir) == {}
    assert os.listdir(mcf.function_dirs(mc_dir)[0]) == []
    load = pdb2mc_function(mc_dir, "load")
    assert "scoreboard objectives remove build_m\n" in load
    assert "build_m" not in pdb2mc_function(mc_dir, "tick")
    assert not any(key.startswith("models/m/") for key in all_functions(mc_dir))


