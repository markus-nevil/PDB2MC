"""
The in-game commands generated by PDB2MC.triggers. These check the generated files. Minecraft itself is not
part of the test suite: the commands were tried by hand on real servers, 1.19.4 to 26.3.
"""
import json
import os
import re

import pandas as pd
import pytest

from PDB2MC import build, cli, defaults, minecraft_functions as mcf, triggers
from conftest import preset


def make_model(mc_dir, name, simple=True, positions=((0, 0, 0), (1, 0, 0))):
    df = pd.DataFrame(positions, columns=['X', 'Y', 'Z'])
    mcf.create_nbt(df, f"{name}_backbone", False, mc_dir, {'backbone_atom': 'stone'})
    mcf.finish_nbts(mc_dir, {"simple": simple}, name)
    mcf.create_nbt_delete(name, mc_dir)
    mcf.finish_delete_nbts(mc_dir, name)


def pdb2mc_function(mc_dir, path):
    root = os.path.join(triggers._pack_dir(mc_dir), "data", "pdb2mc", "function")
    with open(os.path.join(root, *path.split("/")) + ".mcfunction") as f:
        return f.read()


def protein_function(mc_dir, name):
    with open(os.path.join(mcf.function_dirs(mc_dir)[1], f"{name}.mcfunction")) as f:
        return f.read()


def all_functions(mc_dir):
    root = os.path.join(triggers._pack_dir(mc_dir), "data", "pdb2mc", "function")
    found = {}
    for folder, _, files in os.walk(root):
        for filename in files:
            path = os.path.join(folder, filename)
            key = os.path.relpath(path, root)[:-len(".mcfunction")].replace(os.sep, "/")
            with open(path) as f:
                found[key] = f.read()
    return found


def test_every_build_gets_a_lasting_number(mc_dir):
    make_model(mc_dir, "aaa")
    make_model(mc_dir, "bbb")
    assert triggers.install_model(mc_dir, "aaa", mode="Skeleton", scale=2.0) == 1
    assert triggers.install_model(mc_dir, "bbb", mode="Ribbon", scale=1.0) == 2
    make_model(mc_dir, "aaa")                                        # rebuilt
    assert triggers.install_model(mc_dir, "aaa", mode="Custom", scale=2.0) == 1
    assert triggers.model_number(mc_dir, "BBB") == 2
    assert triggers.models(mc_dir)["aaa"]["mode"] == "Custom"


def test_triggers_exist_by_number_and_by_name(mc_dir):
    make_model(mc_dir, "my-gfp")
    triggers.install_model(mc_dir, "my-gfp")
    load = pdb2mc_function(mc_dir, "load")
    tick = pdb2mc_function(mc_dir, "tick")
    for objective in ("models", "build", "delete", "plot", "spawn",
                      "build_my-gfp", "delete_my-gfp", "plot_my-gfp"):
        assert f"scoreboard objectives add {objective} trigger\n" in load
        assert f"scoreboard players enable @a {objective}\n" in tick
    for trigger in ("build", "delete", "plot"):
        assert 'matches 1 run function pdb2mc:' in pdb2mc_function(mc_dir, f"number/{trigger}")
        assert '{name:"my-gfp"}' in pdb2mc_function(mc_dir, f"number/{trigger}")
        assert f"scores={{{trigger}_my-gfp=1..}}" in tick


def test_the_list_shows_every_model(mc_dir):
    make_model(mc_dir, "aaa")
    make_model(mc_dir, "bbb")
    triggers.install_model(mc_dir, "aaa", mode="Skeleton")
    triggers.install_model(mc_dir, "bbb", mode="Ribbon")
    text = pdb2mc_function(mc_dir, "list")
    assert 'placed."aaa"' in text and 'placed."bbb"' in text
    for line in text.splitlines():
        if line.startswith("tellraw"):
            json.loads(line.split(" ", 2)[2])         # valid text component
    assert '"1  "' in text and '"2  "' in text


def test_empty_world_has_an_empty_list(mc_dir):
    triggers.sync(mc_dir)
    assert "No PDB2MC models" in pdb2mc_function(mc_dir, "list")


def test_plain_function_commands_still_build_and_clear(mc_dir):
    make_model(mc_dir, "m")
    triggers.install_model(mc_dir, "m")
    # Through the queue where macros exist, directly where they don't: #found stays 0 then
    build_text = protein_function(mc_dir, "build_m")
    assert "function pdb2mc:models/m/queue" in build_text
    assert "if score #found pdb2mc matches 0 run function pdb2mc:models/m/build" in build_text
    clear_text = protein_function(mc_dir, "clear_m")
    assert "function pdb2mc:models/m/delete" in clear_text
    assert "if score #found pdb2mc matches 0 run function pdb2mc:models/m/clear" in clear_text
    assert "place template mc:m_backbone_part0" in pdb2mc_function(mc_dir, "models/m/build")
    assert "place template mc:delete_m_backbone_part0" in pdb2mc_function(mc_dir, "models/m/clear")
    assert pdb2mc_function(mc_dir, "models/m/build").rstrip().endswith("function pdb2mc:models/m/placed")


def test_files_that_older_minecraft_must_parse_have_no_macros(mc_dir):
    """Before 1.20.2 a macro stops a function from loading, so these must stay plain or the fallback is lost."""
    make_model(mc_dir, "m")
    triggers.install_model(mc_dir, "m")
    plain = [protein_function(mc_dir, "build_m"), protein_function(mc_dir, "clear_m"), pdb2mc_function(mc_dir, "load"),
             pdb2mc_function(mc_dir, "models/m/build"), pdb2mc_function(mc_dir, "models/m/clear")]
    for text in plain:
        assert not any(line.startswith("$") for line in text.splitlines())
        assert '{name:' not in text


def test_per_part_functions_are_remembered_too(mc_dir):
    make_model(mc_dir, "m", simple=False)
    triggers.install_model(mc_dir, "m")
    assert "function pdb2mc:models/m/placed" in protein_function(mc_dir, "build_m_backbone_part0")
    assert "place template mc:m_backbone_part0" in protein_function(mc_dir, "build_m_backbone_part0")
    # Triggers build the whole model even though no single function does
    assert "place template mc:m_backbone_part1" in pdb2mc_function(mc_dir, "models/m/build")


def test_repeating_install_does_not_pile_up_lines(mc_dir):
    make_model(mc_dir, "m", simple=False)
